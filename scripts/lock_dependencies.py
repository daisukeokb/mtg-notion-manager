"""Phase 3H-R2: regenerate requirements/ci-lock.txt (pinned versions + hashes).

The lock covers every third-party distribution CI and the Layer B image
install: the runtime and `dev` dependencies of the main project, plus the build
backends of both local projects (installed with --no-build-isolation so that
they are hash-checked too). It is resolved for the CI target (CPython 3.14,
manylinux x86_64) and lists the sha256 of every published file of each pinned
version, so `pip install --require-hashes` accepts whichever artifact pip picks.

Phase 3H-R4: pip's --python-version/--platform only select wheels; it evaluates
environment markers (`python_version < "3.11"`, ...) with the interpreter that
runs this script. The resolved set is therefore re-walked from the requirements
with the markers evaluated for TARGET_ENVIRONMENT: distributions the target
does not need are left out, and a dependency the target needs that the
resolution did not include is an error. The versions already in the lock are
kept as constraints (minimal change); pass --upgrade to resolve the newest.

Usage (needs network access to PyPI; reads no credentials and never imports or
builds repository code):

    python -I scripts/lock_dependencies.py             # both lock files
    python -I scripts/lock_dependencies.py --upgrade   # both, newest versions
    python -I scripts/lock_dependencies.py --pip-only  # only ci-pip-lock.txt

Phase 3H-R3: it also writes requirements/ci-pip-lock.txt, the pip installed on
the CI runner by scripts/bootstrap_locked_pip.sh (PIP_VERSION below; only the
py3-none-any wheel hash, because the bootstrap verifies that file itself).

Review the diff of the lock files before committing them.
"""

from __future__ import annotations

import json
import re
import subprocess
import sys
import tempfile
import urllib.request
from pathlib import Path

from packaging.requirements import Requirement
from packaging.utils import canonicalize_name

try:
    import tomllib  # type: ignore[import-not-found]
except ModuleNotFoundError:  # Python < 3.11
    import tomli as tomllib

REPO_ROOT = Path(__file__).resolve().parent.parent
PYPROJECTS = (
    REPO_ROOT / "pyproject.toml",
    REPO_ROOT / "tools" / "generation_workspace" / "pyproject.toml",
)
LOCK = REPO_ROOT / "requirements" / "ci-lock.txt"
PIP_LOCK = REPO_ROOT / "requirements" / "ci-pip-lock.txt"
#: pip on the CI runner (requires-python must include the CI Python, 3.14).
PIP_VERSION = "26.0.1"
# hatchling's get_requires_for_build_editable (needed by `pip install -e` with
# --no-build-isolation; build isolation would fetch it without hash checking).
EDITABLE_BUILD_REQUIRES = ["editables"]

#: The CI Python (the Layer B image and setup-python use exactly this version).
TARGET_PYTHON = "3.14.10"
_TARGET_MINOR = ".".join(TARGET_PYTHON.split(".")[:2])
TARGET = [
    "--platform", "manylinux_2_28_x86_64",
    "--platform", "manylinux_2_17_x86_64",
    "--platform", "manylinux2014_x86_64",
    "--python-version", _TARGET_MINOR,
    "--implementation", "cp",
    "--abi", "cp" + _TARGET_MINOR.replace(".", ""),
    "--only-binary=:all:",
]
#: Environment markers of the CI target (CPython on x86_64 Linux).
TARGET_ENVIRONMENT = {
    "implementation_name": "cpython",
    "implementation_version": TARGET_PYTHON,
    "os_name": "posix",
    "platform_machine": "x86_64",
    "platform_python_implementation": "CPython",
    "platform_system": "Linux",
    "python_full_version": TARGET_PYTHON,
    "python_version": _TARGET_MINOR,
    "sys_platform": "linux",
}

HEADER = f"""\
# Phase 3H-R2: pinned, hash-verified dependencies for CI and the Layer B image.
# GENERATED by scripts/lock_dependencies.py; do not edit by hand.
# Target: CPython {_TARGET_MINOR} / manylinux x86_64.
# Install with:
#   pip install --require-hashes --no-deps --only-binary=:all: -r requirements/ci-lock.txt
"""

PIP_HEADER = """\
# Phase 3H-R3: the pip used on the CI runner (hash of the py3-none-any wheel).
# GENERATED by scripts/lock_dependencies.py; do not edit by hand.
# Installed by scripts/bootstrap_locked_pip.sh right after setup-python.
"""


def requirement_specs() -> list[str]:
    specs: list[str] = []
    for path in PYPROJECTS:
        data = tomllib.loads(path.read_text(encoding="utf-8"))
        project = data.get("project", {})
        specs += project.get("dependencies", [])
        specs += project.get("optional-dependencies", {}).get("dev", [])
        specs += data.get("build-system", {}).get("requires", [])
    return sorted(set(specs + EDITABLE_BUILD_REQUIRES))


def locked_versions() -> list[str]:
    """The `name==version` pins of the current lock (empty when there is none)."""
    if not LOCK.exists():
        return []
    return re.findall(r"^([A-Za-z0-9_.-]+==[^ \\]+)", LOCK.read_text(encoding="utf-8"), re.M)


def resolve(specs: list[str], constraints: list[str], workdir: Path) -> list[dict]:
    requirements_in = workdir / "requirements.in"
    requirements_in.write_text("\n".join(specs) + "\n", encoding="utf-8")
    constraints_in = workdir / "constraints.txt"
    constraints_in.write_text("".join(f"{pin}\n" for pin in constraints), encoding="utf-8")
    report = workdir / "report.json"
    subprocess.run(
        [
            sys.executable, "-I", "-m", "pip", "install", "--quiet", "--dry-run",
            "--ignore-installed", "--report", str(report), "--target", str(workdir / "t"),
            *TARGET, "-c", str(constraints_in), "-r", str(requirements_in),
        ],
        check=True,
    )
    return json.loads(report.read_text(encoding="utf-8"))["install"]


def _applies(requirement: Requirement, extra: str) -> bool:
    return requirement.marker is None or requirement.marker.evaluate(
        {**TARGET_ENVIRONMENT, "extra": extra}
    )


class TargetMismatch(ValueError):
    """The target needs `requirement`, which the resolution does not satisfy."""

    def __init__(self, requirement: Requirement, detail: str) -> None:
        super().__init__(f"{requirement} is needed on the CI target, {detail}")
        self.requirement = requirement


def target_closure(specs: list[str], items: list[dict]) -> list[dict]:
    """The resolved distributions the CI target needs, with its markers.

    Raises TargetMismatch when the target needs a distribution (or version)
    that the resolution does not contain.
    """
    by_name = {canonicalize_name(item["metadata"]["name"]): item for item in items}
    seen: set[tuple[str, str]] = set()
    pending = [(Requirement(spec), "") for spec in specs]
    while pending:
        requirement, extra = pending.pop()
        if not _applies(requirement, extra):
            continue
        name = canonicalize_name(requirement.name)
        if name not in by_name:
            raise TargetMismatch(requirement, "not resolved")
        version = by_name[name]["metadata"]["version"]
        if not requirement.specifier.contains(version, prereleases=True):
            raise TargetMismatch(requirement, f"resolved {version}")
        for wanted in ("", *sorted(requirement.extras)):
            if (name, wanted) not in seen:
                seen.add((name, wanted))
                pending += [(Requirement(dependency), wanted)
                            for dependency in by_name[name]["metadata"].get("requires_dist", [])]
    return [by_name[name] for name in sorted({name for name, _ in seen})]


def published_files(name: str, version: str) -> list[dict]:
    url = f"https://pypi.org/pypi/{name}/{version}/json"
    with urllib.request.urlopen(url, timeout=60) as response:  # noqa: S310 (fixed https URL)
        return list(json.load(response)["urls"])


def published_hashes(name: str, version: str) -> list[str]:
    return sorted({f["digests"]["sha256"] for f in published_files(name, version)})


def write_pip_lock() -> int:
    filename = f"pip-{PIP_VERSION}-py3-none-any.whl"
    wheels = [f for f in published_files("pip", PIP_VERSION) if f["filename"] == filename]
    if len(wheels) != 1:
        print(f"ERROR: PyPI does not list exactly one {filename}", file=sys.stderr)
        return 1
    digest = wheels[0]["digests"]["sha256"]
    PIP_LOCK.write_text(
        PIP_HEADER + f"pip=={PIP_VERSION} \\\n    --hash=sha256:{digest}\n", encoding="utf-8"
    )
    print(f"wrote {PIP_LOCK.relative_to(REPO_ROOT)} (pip {PIP_VERSION})")
    return 0


def main() -> int:
    if sys.argv[1:] not in ([], ["--pip-only"], ["--upgrade"]):
        print("usage: lock_dependencies.py [--pip-only | --upgrade]", file=sys.stderr)
        return 2
    if write_pip_lock() != 0:
        return 1
    if sys.argv[1:] == ["--pip-only"]:
        return 0
    lines = [HEADER]
    specs = requirement_specs()
    constraints = [] if sys.argv[1:] == ["--upgrade"] else locked_versions()
    # A requirement only the target needs (its marker is false for this
    # interpreter) is passed to pip explicitly, and its pin is lifted.
    target_specs: list[str] = []
    for _ in range(20):
        with tempfile.TemporaryDirectory() as tmp:
            resolved = resolve(specs + target_specs, constraints, Path(tmp))
        try:
            items = target_closure(specs, resolved)
            break
        except TargetMismatch as exc:
            needed = exc.requirement
            spec = f"{needed.name}{needed.specifier}"
            if spec in target_specs:
                print(f"ERROR: {exc}", file=sys.stderr)
                return 1
            print(f"{exc}: resolving again with {spec}")
            target_specs.append(spec)
            name = canonicalize_name(needed.name)
            constraints = [pin for pin in constraints
                           if canonicalize_name(pin.split("==")[0]) != name]
    else:
        print("ERROR: the target requirements did not converge", file=sys.stderr)
        return 1
    for item in sorted(items, key=lambda i: i["metadata"]["name"].lower()):
        name, version = item["metadata"]["name"], item["metadata"]["version"]
        hashes = published_hashes(name, version)
        chosen = item["download_info"].get("archive_info", {}).get("hashes", {}).get("sha256")
        if not hashes or (chosen and chosen not in hashes):
            print(f"ERROR: PyPI hashes for {name}=={version} do not match the resolved file",
                  file=sys.stderr)
            return 1
        entry = [f"{name.lower()}=={version}"] + [f"    --hash=sha256:{h}" for h in hashes]
        lines.append(" \\\n".join(entry) + "\n")
    LOCK.parent.mkdir(exist_ok=True)
    LOCK.write_text("".join(lines), encoding="utf-8")
    print(f"wrote {LOCK.relative_to(REPO_ROOT)} ({len(items)} packages)")
    omitted = sorted({i["metadata"]["name"] for i in resolved}
                     - {i["metadata"]["name"] for i in items})
    if omitted:
        print(f"not needed on CPython {TARGET_PYTHON} (markers): {', '.join(omitted)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
